/** База знаний помощника: как устроен сайт и как в нём что сделать. Источник для подсказок без модели и для подсказки модели. */
export type AssistantRole = 'guest' | 'user' | 'organizer' | 'admin';
export type AssistantActionType =
  | 'navigate'
  | 'search_events'
  | 'create_event'
  | 'join_event'
  | 'leave_event'
  | 'create_companion'
  | 'favorite_event'
  | 'update_profile';
export interface KnowledgeTopic {
  id: string; // kebab-case, уникальный
  title: string; // «Как записаться на встречу»
  /** Основы слов в нижнем регистре, ё→е, без знаков: по ним помощник узнаёт вопрос. 4–12 штук, разные формулировки людей («запис», «пойти на», «участв», «хочу на игру»). */
  keywords: string[];
  answer: string; // 1–3 коротких предложения: суть
  steps: string[]; // 2–7 шагов: «Откройте «Мои занятия» в меню профиля», «Нажмите «Записаться»»
  links: { label: string; to: string }[]; // 1–3 реальных пути сайта (без домена), label — глагол: «Открыть мои занятия»
  /** Что помощник может сделать сам вместо человека (если применимо). */
  action?: AssistantActionType;
  /** Кому тема актуальна; не указано — всем. */
  roles?: AssistantRole[];
}
export interface SitePage {
  path: string;
  title: string;
  what: string;
  roles?: AssistantRole[];
}

