type Vars = Record<(typeof VARS)[number], string>;

/** Значения токенов берутся из CSS-переменных текущей темы: у цветов один источник — tokens.css. */
export function readCssVars(): Vars {
  const style = getComputedStyle(document.documentElement);
  return Object.fromEntries(VARS.map((name) => [name, style.getPropertyValue(`--${name}`).trim()])) as Vars;
}

