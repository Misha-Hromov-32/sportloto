"""Текстовый поиск без помощника: стоп-слова и основы слов."""

import re
from functools import lru_cache

from app.domain.lib.text import edit_distance, normalize

# Служебные слова, которые не несут смысла для поиска: «хочу на йогу» ищет только «йогу».
STOP_WORDS = frozenset(
    re.split(
        r"\s+",
        "я в во на с со и а но или да не ни же ли бы то ну вот эта этот это эти тот там тут где куда когда как "
        "хочу хочется хотим хотела хотел хотели ищу ищем найти поиск поищу подскажите покажите есть можно нужно надо "
        "пойти сходить пошли идем идти го давай давайте мне меня мой моя мои мое наш наша наши нам нас мы вы вас "
        "вам ты тебе он она они их его ее кто что чтобы чтоб чем для по к ко у о об от до из за при про без над под "
        "тоже также еще ещё очень просто какой какая какую какое какие нибудь либо где-нибудь куда-нибудь что-нибудь "
        "раз уже только совсем вообще примерно около здравствуйте привет пожалуйста спасибо будет будем буду "
        "компанию компания кем-нибудь кого-нибудь кого нибудь людей люди людьми ребята ребят друзья поиграть играть "
        "сыграть позаниматься заниматься попробовать поучаствовать",
    )
)

# Длинные окончания проверяются первыми; окончания одной длины — в порядке списка (сортировка устойчивая).
ENDINGS = sorted(
    [
        "иями", "ями", "ами", "ием", "иях", "ией", "ться", "тся",
        "ого", "его", "ому", "ему", "ыми", "ими", "ешь", "ать", "ять", "ить", "еть", "уть",
        "ют", "ут", "ет", "ит", "ах", "ях", "ой", "ей", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие",
        "ую", "юю", "ом", "ем", "ам", "ям", "ов", "ев", "ью", "ья", "ье", "ьи", "ия", "ии",
        "а", "я", "о", "е", "ы", "и", "у", "ю", "ь", "й",
    ],
    key=len,
    reverse=True,
)  # fmt: skip

_DIGIT = re.compile(r"[0-9]")


@lru_cache(maxsize=32768)
def stem_ru(word: str) -> str:
    """Основа слова: отбрасываем падежное или глагольное окончание, оставляя не меньше трёх букв.

    «йогу», «йогой» → «йог»; «городки» → «городк» и не совпадает с «городе» → «город».
    """
    if len(word) <= 3 or _DIGIT.search(word):
        return word
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[: -len(ending)]
    return word


@lru_cache(maxsize=65536)
def word_matches(word: str, term: str) -> bool:
    """Совпадает ли слово из текста со словом термина с учётом окончаний и опечаток в длинных словах."""
    if word == term:
        return True
    a = stem_ru(word)
    b = stem_ru(term)
    if a == b:
        return True
    # «шахматный» → «шахмат», «волейбольный» → «волейбол»: слово длиннее термина на суффикс
    if len(b) >= 5 and a.startswith(b) and len(a) - len(b) <= 3:
        return True
    return len(b) >= 7 and len(a) >= 7 and abs(len(a) - len(b)) <= 1 and edit_distance(a, b) <= 1


def words(text: str) -> list[str]:
    return [w for w in normalize(text).split(" ") if w]


def query_words(query: str) -> list[str]:
    """Значимые слова запроса: без служебных и коротких."""
    return [w for w in words(query) if w not in STOP_WORDS and (len(w) > 2 or _DIGIT.search(w))]


def text_matches(query: str, haystack: str) -> bool:
    """Текстовый поиск без помощника: каждое значимое слово запроса должно найтись в тексте.

    С учётом окончаний: «хочу на йогу» находит «Йога на набережной».
    """
    q = query_words(query)
    if not q:
        return True
    hay = words(haystack)
    return all(any(word_matches(h, w) or (len(w) >= 4 and h.startswith(w)) for h in hay) for w in q)
