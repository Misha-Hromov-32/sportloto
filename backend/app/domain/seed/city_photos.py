def _url(key: str, query: str) -> str:
    return f"{_BASE}{PHOTOS[key]}?{query}"


def cover(key: str) -> str:
    """Обложка встречи или клуба, площадка: ширина 900, пропорции снимка."""
    return _url(key, "w=900&q=70&auto=format&fit=crop")


